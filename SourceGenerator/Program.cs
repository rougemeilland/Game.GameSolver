                    sourceWriter.WriteLine("    {");
                    sourceWriter.WriteLine("        private static readonly byte[][] _visibleCellsIndexes =");
                    sourceWriter.WriteLine("        [");

                    for (var cellIndex = 0; cellIndex < 81; ++cellIndex)
                    {
                        var column = cellIndex % 9;
                        var row = cellIndex / 9;
                        var blockColumn = column / 3;
                        var blockRow = row / 3;
                        var indexList = new List<int>();

                        // 横方向のハウスのインデックスの追加
                        for (var count = 0; count < 9; ++count)
                        {
                            var index = row * 9 + count;
                            if (index != cellIndex)
                            {
                                if (index is < 0 or >= 81)
                                    throw new ApplicationException();
                                indexList.Add(index);
                            }
                        }

                        // 縦方向のハウスのインデックスの追加
                        for (var count = 0; count < 9; ++count)
                        {
                            var index = column + count * 9;
                            if (index != cellIndex)
                            {
                                if (index is < 0 or >= 81)
                                    throw new ApplicationException();
                                indexList.Add(index);
                            }
                        }

