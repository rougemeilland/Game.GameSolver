                        for (var rowCount = 0; rowCount < 3; ++rowCount)
                        {
                            for (var columnCount = 0; columnCount < 3; ++columnCount)
                            {
                                var index = blockRow * 27 + blockColumn * 3 + rowCount * 9 + columnCount;
                                if (index != cellIndex)
                                {
                                    if (index is < 0 or >= 81)
                                        throw new ApplicationException();
                                    indexList.Add(index);
                                }
                            }
                        }

                        sourceWriter.WriteLine($"            [ {string.Join(", ", indexList.Distinct().OrderBy(n => n).Select(n => $"{n:D2}"))} ],");
                    }

                    sourceWriter.WriteLine("        ];");
                    sourceWriter.WriteLine();
                    sourceWriter.WriteLine("        /// <summary>");
                    sourceWriter.WriteLine("        /// 全ての未確定セルの数字のメモの数の合計値を求めます。");
                    sourceWriter.WriteLine("        /// </summary>");
                    sourceWriter.WriteLine("        /// <returns>");
                    sourceWriter.WriteLine("        /// 全ての未確定セルの数字のメモの数の合計値を示す <see cref=\"int\"/> 値です。");
